-- ============================================================================
-- FocusGuard — Database Setup Script
-- Matches the current live schema of the application (MySQL 8.x).
--
-- HOW TO USE:
--   1. Install MySQL 8 and make sure the server is running on localhost:3306.
--   2. Open the script in MySQL Workbench / MySQL Shell, or run from a terminal:
--        mysql -u root -p < database-setup.sql
--   3. Edit src/main/java/com/focusguard/DBConnection.java and set your own
--      MySQL username and password.
--   4. Start the app and register a new account on the "Create an account" screen.
--
-- NOTE: Do NOT create user accounts by inserting rows here — passwords are
-- PBKDF2-HMAC-SHA256 hashes (format: pbkdf2$iterations$salt$hash) generated by
-- the app. Just register through the UI.
-- ============================================================================

CREATE DATABASE IF NOT EXISTS focusguard_db
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_0900_ai_ci;

USE focusguard_db;

-- ---------------------------------------------------------------------------
-- users — login accounts (created through RegisterFrame / UserDAO)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    user_id       INT          NOT NULL AUTO_INCREMENT,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id),
    UNIQUE KEY uq_users_email (email)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------------
-- focus_sessions — one row per timer session started in the Focus page
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS focus_sessions (
    session_id       INT  NOT NULL AUTO_INCREMENT,
    mode             VARCHAR(30) DEFAULT 'Study',
    technique        VARCHAR(30) DEFAULT 'Pomodoro',
    start_time       DATETIME    NOT NULL,
    end_time         DATETIME    DEFAULT NULL,
    duration_minutes INT         DEFAULT 25,
    status           ENUM('Active','Paused','Completed','Stopped') DEFAULT 'Active',
    elapsed_seconds  INT         NOT NULL DEFAULT 0,
    PRIMARY KEY (session_id)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------------
-- tasks — the task list (Tasks page, profile stats, overdue filters)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tasks (
    task_id     INT          NOT NULL AUTO_INCREMENT,
    title       VARCHAR(150) NOT NULL,
    description VARCHAR(500) DEFAULT NULL,
    priority    ENUM('Low','Medium','High') DEFAULT 'Medium',
    status      ENUM('Pending','Completed') DEFAULT 'Pending',
    due_date    DATE         DEFAULT NULL,
    created_at  TIMESTAMP    NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (task_id)
) ENGINE = InnoDB;

